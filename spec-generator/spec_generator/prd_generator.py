"""Generate PRD Markdown from the spec result."""
import json
from datetime import datetime


def generate_prd(business_description: str, requirements: dict, data_models: dict, state_machines: dict, test_cases: dict, review: dict) -> str:
    """Generate a structured PRD in Markdown format."""
    lines = [
        f"# Product Requirements Document (PRD)",
        f"",
        f"**Generated**: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"**Source**: AI-generated from business description",
        f"",
        f"## 1. Business Description",
        f"",
        business_description,
        f"",
    ]

    # Requirements
    reqs = requirements.get("requirements", [])
    if reqs:
        lines.append("## 2. Requirements")
        lines.append("")
        lines.append("| # | Category | Description | Priority |")
        lines.append("|---|---|---|---|")
        for i, r in enumerate(reqs, 1):
            lines.append(f"| {i} | {r.get('category', '')} | {r.get('description', '')} | {r.get('priority', '')} |")
        lines.append("")

    # User Roles
    roles = requirements.get("user_roles", [])
    if roles:
        lines.append("## 3. User Roles")
        lines.append("")
        for r in roles:
            perms = ", ".join(r.get("permissions", []))
            lines.append(f"### {r.get('name', '')}")
            lines.append(f"{r.get('description', '')}")
            lines.append(f"**Permissions**: {perms}")
            lines.append("")

    # Use Cases
    use_cases = requirements.get("use_cases", [])
    if use_cases:
        lines.append("## 4. Key Use Cases")
        lines.append("")
        for i, uc in enumerate(use_cases, 1):
            lines.append(f"{i}. {uc}")
        lines.append("")

    # Data Models
    models = data_models.get("models", [])
    if models:
        lines.append("## 5. Data Model")
        lines.append("")
        for m in models:
            lines.append(f"### {m.get('name', '')}")
            lines.append(f"{m.get('description', '')}")
            lines.append("")
            lines.append("| Field | Type | Required | Validation | Description |")
            lines.append("|---|---|---|---|---|")
            for f in m.get("fields", []):
                lines.append(f"| {f.get('name', '')} | {f.get('type', '')} | {'✅' if f.get('required') else ''} | {f.get('validation', '')} | {f.get('description', '')} |")
            lines.append("")

    # State Machines
    sms = state_machines.get("state_machines", [])
    if sms:
        lines.append("## 6. State Machines")
        lines.append("")
        for sm in sms:
            lines.append(f"### {sm.get('entity', '')}")
            lines.append(f"**Initial state**: `{sm.get('initial_state', '')}`")
            lines.append(f"**States**: {', '.join(f'`{s}`' for s in sm.get('states', []))}")
            lines.append("")
            lines.append("| From | To | Trigger | Guard |")
            lines.append("|---|---|---|---|")
            for t in sm.get("transitions", []):
                lines.append(f"| {t.get('from_state', '')} | {t.get('to_state', '')} | {t.get('trigger', '')} | {t.get('guard', '')} |")
            lines.append("")

    # Test Cases
    tcs = test_cases.get("test_cases", [])
    if tcs:
        lines.append("## 7. Test Cases")
        lines.append("")
        for tc in tcs:
            lines.append(f"### {tc.get('id', '')}: {tc.get('title', '')}")
            lines.append(f"**Category**: {tc.get('category', '')}")
            lines.append(f"**Steps**:")
            for s in tc.get("steps", []):
                lines.append(f"  - {s}")
            lines.append(f"**Expected**: {tc.get('expected_result', '')}")
            lines.append("")

    # Review
    issues = review.get("issues", [])
    if issues:
        lines.append("## 8. Review Notes")
        lines.append("")
        lines.append(f"**Overall**: {review.get('overall_assessment', '')}")
        lines.append("")
        lines.append("| Severity | Category | Issue | Recommendation |")
        lines.append("|---|---|---|---|")
        for issue in issues:
            lines.append(f"| {issue.get('severity', '')} | {issue.get('category', '')} | {issue.get('description', '')} | {issue.get('recommendation', '')} |")
        lines.append("")

        missing = review.get("missing_test_cases", [])
        if missing:
            lines.append("### Missing Test Cases")
            lines.append("")
            for m in missing:
                lines.append(f"- {m}")
            lines.append("")

    lines.append("---")
    lines.append(f"*Generated by Product Spec Generator at {datetime.now().isoformat()}*")

    return "\n".join(lines)